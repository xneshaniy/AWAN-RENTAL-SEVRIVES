/** A single settings key accepted from admin input. */
export const settingKeySchema = z
  .string()
  .regex(/^[a-z0-9_-]{1,64}$/, 'Invalid setting key');

/**
 * Server-side validation for settings updates. Never trust the client:
 * keys must match the known key shape (no prototype tricks), values are
 * bounded, and URL-like keys may only hold safe link values - some
 * settings are rendered straight into `href` attributes on public pages,
 * so `javascript:` and similar schemes must never be stored.
 */
export const settingsUpdateSchema = z
  .record(settingKeySchema, z.string().max(50000, 'Setting value is too long'))
  .refine(
    (record) =>
      Object.entries(record).every(
        ([key, value]) =>
          !/(url|image|photo)/.test(key) ||
          value === '' ||
          /^(https?:\/\/|\/|#|mailto:|tel:)/.test(value)
      ),
    { message: 'Link settings must start with https://, http://, /, #, mailto: or tel:' }
  );


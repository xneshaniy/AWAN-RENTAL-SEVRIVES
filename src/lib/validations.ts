const DATE_PATTERN = /^\d{4}-\d{2}-\d{2}$/;
const TIME_PATTERN = /^([01]\d|2[0-3]):[0-5]\d$/;

/**
 * Airport-transfer request form. Field names mirror `bookingSchema`
 * (direction/rentalType, date+time/pickupDate+pickupTime, location/
 * pickupLocation, passengers, luggage, flightNumber) so the payload can be
 * handed to the Booking system later without reshaping it.
 *
 * Airport availability is validated against the configured
 * `AIRPORT_OPTIONS` list, so disabled airports can never be submitted.
 */
export const airportTransferSchema = z.object({
  airport: z.string().min(1, 'Please select an airport'),
  direction: z.enum(['ARRIVAL', 'DEPARTURE'], {
    required_error: 'Please select arrival or departure',
    invalid_type_error: 'Please select arrival or departure',
  }),
  date: z.string().min(1, 'Date is required'),
  time: z.string().min(1, 'Time is required'),
  flightNumber: z
    .string()
    .max(12, 'Flight number is too long')
    .regex(/^[A-Za-z0-9 -]+$/, 'Use letters and numbers only')
    .optional()
    .or(z.literal('')),
  location: z
    .string()
    .trim()
    .min(5, 'Enter the pickup or drop-off location')
    .max(200),
  passengers: z.coerce
    .number()
    .min(1, 'At least 1 passenger')
    .max(50, 'Maximum 50 passengers — contact us for larger groups'),
  luggage: z.coerce
    .number()
    .min(0, 'Luggage cannot be negative')
    .max(20, 'Maximum 20 pieces'),
  vehiclePreference: z.enum(VEHICLE_PREFERENCE_VALUES, {
    required_error: 'Please select a vehicle preference',
    invalid_type_error: 'Please select a vehicle preference',
  }),
  customerName: z.string().trim().min(2, 'Name must be at least 2 characters').max(100),
  whatsapp: z
    .string()
    .trim()
    .min(1, 'WhatsApp number is required')
    .refine((value) => {
      const digits = value.replace(/\D/g, '');
      return digits.length >= 10 && digits.length <= 15;
    }, 'Enter a valid WhatsApp number (e.g., +92 3XX XXXXXXX)'),
  honeypot: z.string().optional(),
})
  .superRefine((data, ctx) => {
    if (!data.airport) return;
    const allowed = getEnabledAirportIds();
    if (ALLOW_OTHER_AIRPORT) allowed.push(OTHER_AIRPORT_ID);
    if (!allowed.includes(data.airport)) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        path: ['airport'],
        message: 'Please select a valid airport',
      });
    }
  })
  .refine((data) => !data.date || DATE_PATTERN.test(data.date), {
    message: 'Enter a valid date',
    path: ['date'],
  })
  .refine((data) => !data.time || TIME_PATTERN.test(data.time), {
    message: 'Enter a valid time (HH:MM)',
    path: ['time'],
  })
  .refine((data) => {
    if (!DATE_PATTERN.test(data.date) || !TIME_PATTERN.test(data.time)) return true;
    const transferAt = new Date(`${data.date}T${data.time}`);
    // 12-hour grace so server/client timezone differences never reject a
    // genuinely upcoming transfer; clearly past dates are still rejected.
    return transferAt.getTime() > Date.now() - 12 * 60 * 60 * 1000;
  }, {
    message: 'Transfer date and time must be in the future',
    path: ['date'],
  })
  .refine((data) => !data.honeypot, {
    message: 'Spam detected',
    path: ['honeypot'],
  });

/**
 * Image fields must accept an empty string (react-hook-form sends '' for an
 * untouched optional input) and site paths like /vehicles/car.jpg, which the
 * admin placeholders document. Empty input is normalised to null so it is
 * never stored as ''.
 */
const imageSource = z
  .string()
  .trim()
  .refine(
    (value) => value.startsWith('/') || /^https?:\/\//.test(value),
    'Image must be a site path (/...) or an http(s) URL'
  );

const optionalImageSource = z
  .string()
  .trim()
  .refine(
    (value) => value === '' || value.startsWith('/') || /^https?:\/\//.test(value),
    'Image must be empty, a site path (/...) or an http(s) URL'
  )
  .optional()
  .nullable()
  .transform((value) => (value === '' ? null : value));


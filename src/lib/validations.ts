export const bookingSchema = z.object({
  customerName: z.string().min(2, 'Name must be at least 2 characters').max(100),
  customerEmail: z.string().email('Invalid email address'),
  customerPhone: z.string().min(10, 'Phone number must be at least 10 digits').max(20),
  customerWhatsApp: z.string().min(10, 'WhatsApp number must be at least 10 digits').max(20).optional().or(z.literal('')),
  vehicleId: z.string().min(1, 'Please select a vehicle'),
  rentalType: z.enum(['SELF_DRIVE', 'CHAUFFEUR', 'AIRPORT_TRANSFER', 'CORPORATE', 'OTHER']),
  pickupLocation: z.string().min(2, 'Pickup location is required').max(200),
  dropoffLocation: z.string().min(2, 'Drop-off location is required').max(200),
  pickupDate: z.string().min(1, 'Pickup date is required'),
  pickupTime: z.string().min(1, 'Pickup time is required'),
  returnDate: z.string().min(1, 'Return date is required'),
  returnTime: z.string().min(1, 'Return time is required'),
  flightNumber: z.string().max(50).optional().or(z.literal('')),
  passengers: z.coerce.number().min(1, 'At least 1 passenger').max(50),
  luggage: z.coerce.number().min(0).max(20).optional(),
  specialRequests: z.string().max(1000).optional().or(z.literal('')),
  /**
   * Idempotency key for duplicate submission protection. Generated by the
   * form (one per submission attempt) and enforced by the unique constraint
   * on `Booking.submissionId` - the server-side check never trusts the client.
   */
  submissionId: z.string().uuid('Invalid submission id').optional().or(z.literal('')),
  honeypot: z.string().optional(),
}).refine((data) => {
  const pickup = new Date(`${data.pickupDate}T${data.pickupTime}`);
  const returnDate = new Date(`${data.returnDate}T${data.returnTime}`);
  return returnDate > pickup;
}, {
  message: 'Return date/time must be after pickup date/time',
  path: ['returnDate'],
}).refine((data) => {
  const pickup = new Date(`${data.pickupDate}T${data.pickupTime}`);
  return pickup > new Date();
}, {
  message: 'Pickup date/time must be in the future',
  path: ['pickupDate'],
}).refine((data) => !data.honeypot, {
  message: 'Spam detected',
  path: ['honeypot'],
});

